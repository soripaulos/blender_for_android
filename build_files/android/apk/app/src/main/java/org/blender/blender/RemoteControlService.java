package org.blender.blender;

import android.app.Notification;
import android.app.NotificationChannel;
import android.app.NotificationManager;
import android.app.PendingIntent;
import android.app.Service;
import android.content.Intent;
import android.content.pm.ServiceInfo;
import android.os.Build;
import android.os.IBinder;
import android.util.Log;

/**
 * Keeps Blender running while it is being driven from Termux.
 *
 * The remote control server (scripts/modules/_bpy_internal/remote_control) answers on a
 * loopback socket, and the user is by definition looking at another app while it does.
 * Without a foreground service a backgrounded app drops to the cached state, where the
 * cached-apps freezer (Android 12+) stops its threads within seconds: the server would
 * accept the connection and then never answer. This service does nothing itself; holding
 * the process in the foreground state is the whole job, and its notification tells the
 * user why Blender is still running.
 *
 * Started and stopped by BlenderActivity, which follows the server's marker file.
 */
public class RemoteControlService extends Service {

  private static final String TAG = "blender";
  private static final String CHANNEL_ID = "remote_control";
  private static final int NOTIFICATION_ID = 0x626c6e64;

  @Override
  public int onStartCommand(Intent intent, int flags, int startId) {
    NotificationManager manager = getSystemService(NotificationManager.class);
    if (manager != null && manager.getNotificationChannel(CHANNEL_ID) == null) {
      NotificationChannel channel = new NotificationChannel(
          CHANNEL_ID, "Remote control", NotificationManager.IMPORTANCE_LOW);
      channel.setDescription("Shown while Termux can control Blender");
      manager.createNotificationChannel(channel);
    }

    Intent open = new Intent(this, BlenderActivity.class);
    open.setFlags(Intent.FLAG_ACTIVITY_NEW_TASK | Intent.FLAG_ACTIVITY_SINGLE_TOP);
    PendingIntent content = PendingIntent.getActivity(
        this, 0, open, PendingIntent.FLAG_IMMUTABLE | PendingIntent.FLAG_UPDATE_CURRENT);

    /* R is not generated by package.sh, so take the icon id from the application. */
    Notification notification = new Notification.Builder(this, CHANNEL_ID)
                                    .setSmallIcon(getApplicationInfo().icon)
                                    .setContentTitle("Blender remote control is on")
                                    .setContentText("blender-cli in Termux can run scripts")
                                    .setContentIntent(content)
                                    .setOngoing(true)
                                    .build();
    try {
      if (Build.VERSION.SDK_INT >= 34) {
        startForeground(NOTIFICATION_ID, notification, ServiceInfo.FOREGROUND_SERVICE_TYPE_SPECIAL_USE);
      }
      else {
        startForeground(NOTIFICATION_ID, notification);
      }
    }
    catch (Exception ex) {
      /* ForegroundServiceStartNotAllowedException and friends: the server still works while
       * Blender is visible, it just may be frozen in the background. */
      Log.w(TAG, "remote control: cannot enter the foreground", ex);
      stopSelf();
    }
    return START_NOT_STICKY;
  }

  @Override
  public IBinder onBind(Intent intent) {
    return null;
  }
}
